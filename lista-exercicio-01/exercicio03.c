/*Esse programa mostra o uso dos comentários na linguagem C*/

#include <stdio.h> /*Para a função printf()*/
#include <stdlib.h> /*Para system()*/


int main() /*Função main*/
{ /*Início do corpo da função*/

    int idade = 19; /*Declaro a variável idade com valor atribuido 19*/
    printf("Oi, tenho %d anos. ", idade); /*Chama a função printf formatando a variavel idade.*/
    system("PAUSE"); /*Chama a função system()*/

    return 0;


}/*Fim do corpo da função*/
